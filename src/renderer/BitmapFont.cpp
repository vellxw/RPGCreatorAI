void BitmapFont::drawText(SDL_Renderer* renderer,
                          int x, int y,
                          const std::string& text,
                          int scale,
                          unsigned char r,
                          unsigned char g,
                          unsigned char b,
                          unsigned char a) {
    if (!renderer || scale < 1) return;
    SDL_SetRenderDrawColor(renderer, r, g, b, a);

    int cursor = x;
    const int colSpace = 1; // 1px gap between glyphs at scale 1
    for (char c : text) {
        const Glyph* glyph = findGlyph(c);
        if (glyph) {
            for (int row = 0; row < GlyphHeight; ++row) {
                std::uint8_t bits = (*glyph)[row];
                for (int col = 0; col < GlyphWidth; ++col) {
                    // Glyphs encoded with bit 4 = leftmost pixel.
                    if (bits & (1 << (GlyphWidth - 1 - col))) {
                        SDL_Rect px{
                            cursor + col * scale,
                            y + row * scale,
                            scale,
                            scale
                        };
                        SDL_RenderFillRect(renderer, &px);
                    }
                }
            }
        }
        cursor += (GlyphWidth + colSpace) * scale;
    }
}

int BitmapFont::measureWidth(const std::string& text, int scale) {
    if (text.empty() || scale < 1) return 0;
    return static_cast<int>(text.size()) * (GlyphWidth + 1) * scale;
}
